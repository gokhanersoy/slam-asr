import sys
import os

# Add src to path
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "../../src")))

from slam_llm.utils.compute_wer import compute_wer

def calculate_wer(pred_file, gt_file, detail_file="wer_detail.txt"):
    """
    Computes WER given prediction file and ground truth file generated by inference_asr_batch.py.
    """
    if not os.path.exists(pred_file):
        raise FileNotFoundError(f"Prediction file not found: {pred_file}")
    if not os.path.exists(gt_file):
        raise FileNotFoundError(f"Ground truth file not found: {gt_file}")

    print(f"Calculating WER comparing:\n  Prediction: {pred_file}\n  Ground Truth: {gt_file}\n")
    compute_wer(gt_file, pred_file, detail_file)

    # Read summary results from detail file
    with open(detail_file, 'r') as f:
        lines = f.readlines()
        summary_lines = [line.strip() for line in lines if line.startswith("%WER") or line.startswith("%SER") or line.startswith("Scored")]
        for line in summary_lines:
            print(line)

if __name__ == "__main__":
    if len(sys.argv) < 3:
        print("Usage: python eval_wer.py <pred_file> <gt_file> [detail_output_file]")
        sys.exit(1)
    
    pred_path = sys.argv[1]
    gt_path = sys.argv[2]
    out_detail = sys.argv[3] if len(sys.argv) > 3 else "wer_detail.txt"
    
    calculate_wer(pred_path, gt_path, out_detail)
